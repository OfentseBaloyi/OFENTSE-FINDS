// Generates supabase/migrations/20261012000100_seed_towns_categories.sql from the app's own
// category registry and town seed data, so the database and the code never drift apart.
// Usage: node scripts/build-seed-sql.mjs   (Node 22.18+ — reads the .ts registry directly)

import { readFile, writeFile } from "node:fs/promises";
import { CATEGORIES, CATEGORY_GROUPS } from "../src/data/categories.ts";

const towns = JSON.parse(await readFile(new URL("../src/data/towns.generated.json", import.meta.url), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? "null" : String(Number(v)));

let sql = `-- OFENTSE-FINDS — seed data (generated by scripts/build-seed-sql.mjs; do not edit by hand)
-- Idempotent: inserts missing rows and refreshes names/descriptions; never deletes anything.

-- Category groups (parent_id null)
insert into public.categories (name, slug, icon, color, description, parent_id, sort_order) values
${CATEGORY_GROUPS.map((g, i) => `  (${q(g.name)}, ${q(g.slug)}, ${q(g.icon)}, ${q(g.color)}, ${q(g.description)}, null, ${i})`).join(",\n")}
on conflict (slug) do update set name = excluded.name, icon = excluded.icon, color = excluded.color, description = excluded.description, sort_order = excluded.sort_order;

-- Categories
insert into public.categories (name, slug, icon, description, parent_id, sort_order)
select v.name, v.slug, v.icon, v.description, p.id, v.sort_order
from (values
${CATEGORIES.map((c, i) => `  (${q(c.name)}, ${q(c.slug)}, ${q(c.icon)}, ${q(c.description)}, ${q(c.group)}, ${i})`).join(",\n")}
) as v(name, slug, icon, description, parent_slug, sort_order)
join public.categories p on p.slug = v.parent_slug
on conflict (slug) do update set name = excluded.name, icon = excluded.icon, description = excluded.description, parent_id = excluded.parent_id, sort_order = excluded.sort_order;

-- Towns (coordinates from OpenStreetMap/Nominatim; descriptions & photos from Wikipedia/Wikimedia Commons)
insert into public.towns (name, slug, province, description, latitude, longitude, kind, radius_km, cover_image_url, cover_image_credit, cover_image_license, cover_image_source_url, wiki_url) values
${towns
  .map(
    (t) =>
      `  (${q(t.name)}, ${q(t.slug)}, ${q(t.province)}, ${q(t.description)}, ${n(t.latitude)}, ${n(t.longitude)}, ${q(t.kind)}, ${n(t.radiusKm)}, ${q(t.cover?.url)}, ${q(t.cover?.credit)}, ${q(t.cover?.license)}, ${q(t.cover?.sourceUrl)}, ${q(t.wikiUrl)})`,
  )
  .join(",\n")}
on conflict (slug) do nothing;
`;

await writeFile(new URL("../supabase/migrations/20261012000100_seed_towns_categories.sql", import.meta.url), sql);
console.log(`Seed SQL written: ${CATEGORY_GROUPS.length} groups, ${CATEGORIES.length} categories, ${towns.length} towns.`);
